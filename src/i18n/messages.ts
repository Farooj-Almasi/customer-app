const CATALOG: Record<Lang, Record<MessageKey, string>> = { en, ar };

/**
 * Translate a key for a language, interpolating `{var}` placeholders. Pure.
 * An unknown key returns the key itself (so a miss is visible, not a crash).
 */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = CATALOG[lang][key] ?? CATALOG.en[key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
